/* ═══ v2.3.5781: ARE BOTH WHEELS' BAKES FROM TODAY'S INPUTS? (card U2 PR 2; CLAUDE.md §8 row "a change to the Wheel's plan or objects") ═══
 *
 * CLAUDE.md §7: "a change to the plan, the object catalog, the placing, or
 * the trees' or rocks' picture sizes re-bakes BOTH Wheels in the same PR".
 * The bakes' own `--check` (tools/world/bake-wheel-spawns.mjs,
 * bake-wheel-world.mjs) re-bakes everything and compares: about 60 s and
 * 26 s on this box, far over a guard's two seconds.  So, as the planning
 * session chose (card U2, "Decided" 1), the guard reads FINGERPRINTS:
 *
 *   - the world bake (objects, overview, lands) writes the plan's own
 *     fingerprint into public/tools/world/core/placed.js (`plan`:
 *     worldblocks.js planFingerprint = the plan, the object catalog and the
 *     placing).  It must be today's, for both Wheels: a few ms.
 *   - the spawns bake (server/src/wheelspawns.js, wheelspawns1.js) keeps a
 *     blueprint hash that costs 20 s to work out, and no fingerprint of its
 *     inputs.  So the guard keeps one: `bakeInputs()` (both plans'
 *     fingerprints, and the trees' and rocks' picture sizes at every level,
 *     the spawns' clearances) beside the spawns files' hashes, in
 *     ./wheelBakesSeen.mjs, written ONLY by
 *     `node tools/guards/wheel-bakes.test.mjs --write`, which runs both
 *     bakes' full `--check` first and writes nothing unless both pass.
 *
 * What it does not see: a change to the bakes' CODE (layout.js, placing.js's
 * functions) that leaves these inputs alone.  test-world-core's `--check`,
 * by hand, still sees that.  Node only (the guards run on GitHub with
 * server/'s packages; these modules import nothing outside the repository).
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLAN, PLAN5 } from '../../../public/tools/world/plan.js';
import { planFingerprint } from '../../../public/tools/world/core/worldblocks.js';
import { fnv1a } from '../../../public/tools/world/core/rng.js';
import { PLACED5, PLACED } from '../../../public/tools/world/core/placed.js';
import { treeGeom, treeChopOffset } from '../../../src/game/tierTrees.js';
import { oreGeom } from '../../../src/game/tierOre.js';

export const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..', '..', '..');
export const SPAWN_FILES = Object.freeze({ long: 'server/src/wheelspawns.js', short: 'server/src/wheelspawns1.js' });

/** The trees' and rocks' picture sizes at every gathering level, as the bake reads them. */
export function sizesFingerprint() {
  const rows = [];
  for (let lvl = 0; lvl <= 120; lvl++) {
    const node = { x: 0, y: 0, gatherLvl: lvl };
    rows.push([lvl, treeGeom(node), treeChopOffset(node), oreGeom(node)]);
  }
  return fnv1a(JSON.stringify(rows));   /* fnv1a gives 8 hex digits */
}

/** The world bake: each Wheel's plan fingerprint today, and the one placed.js was baked from. */
export function worldBakes() {
  return [
    { name: 'PLACED5 (the long Wheel)', now: planFingerprint(PLAN5), baked: PLACED5.plan },
    { name: 'PLACED (the short Wheel)', now: planFingerprint(PLAN), baked: PLACED.plan },
  ];
}

/** Everything the spawns bake reads that a fingerprint can say: both plans (with the catalog and the placing) and the sizes. */
export function bakeInputs() {
  const long = planFingerprint(PLAN5), short = planFingerprint(PLAN), sizes = sizesFingerprint();
  return { long, short, sizes, inputs: fnv1a(long, short, sizes) };
}

/** The hash each spawns file was baked with (WHEEL_SPAWNS_HASH), read as text. */
export function spawnHashes(root = ROOT) {
  const out = {};
  for (const [k, f] of Object.entries(SPAWN_FILES)) {
    const m = /^export const WHEEL_SPAWNS_HASH = '([0-9a-f]+)';$/m.exec(readFileSync(join(root, f), 'utf8'));
    out[k] = m ? m[1] : null;
  }
  return out;
}

/** ./wheelBakesSeen.mjs's text. */
export function renderSeen(seen) {
  return `/* v2.3.5781: GENERATED by \`node tools/guards/wheel-bakes.test.mjs --write\`, which
   writes it only after both Wheels' bakes passed their full \`--check\`
   (tools/world/bake-wheel-spawns.mjs, bake-wheel-world.mjs).  Never edit by
   hand: a hand-written line here is a bake nobody checked.  ./wheelBakes.mjs
   says what each value is. */
export const SEEN = Object.freeze({
  inputs: '${seen.inputs}',
  spawnsLong: '${seen.spawnsLong}',
  spawnsShort: '${seen.spawnsShort}',
});
`;
}
