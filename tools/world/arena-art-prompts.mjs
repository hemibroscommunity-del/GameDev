#!/usr/bin/env node
/* ═══ v2.3.3730: THE ARENA'S FOUR PICTURES, AS THE PROMPTS THE OWNER PASTED ═══
 *
 * The owner made the arena's art in ChatGPT from prompts the Object Studio's
 * own builder made (public/tools/objects/prompts.js promptFor): the rodeo
 * ring, its gate, two stands and four props.  The entries are kept here, not
 * in the studio's catalog.js -- a catalog change re-bakes both Wheels and
 * deploys the worker, and this art comes into the game through
 * src/data/arenaArt.js instead (tools/world/add-arena-art.mjs).
 *
 * Writes docs/art/ARENA-ART-PROMPTS.md, so the record matches what was
 * pasted, word for word.
 *
 *     node tools/world/arena-art-prompts.mjs          # write the doc
 *     node tools/world/arena-art-prompts.mjs --check  # exit 1 if it is stale
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { promptFor } from '../../public/tools/objects/prompts.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DOC = path.join(ROOT, 'docs/art/ARENA-ART-PROMPTS.md');

const A = (o) => ({ group: 'arena', kind: 'prop', count: 1, fit: 'h', frame: 'square', key: 'magenta', ...o });
/* `file` is where the picture that came back is kept (assets/prop-source/arena/) */
export const ARENA_PROMPTS = [
  { file: 'ring.png', entry: A({ id: 'arena-ring', name: 'Rodeo ring', fit: 'w', frame: 'wide', size: 640, what: 'a big round rodeo ring for duels, seen from above at a steep angle so the circle looks like a wide oval: a ring of sturdy log posts joined by three split-log rails all the way round, enclosing open, empty ground, with a wide gap at the front where the entrance is. The ground inside and outside the ring is the background colour, not dirt or grass. A few posts are proudly patched, one rail is held on with rope, and a horseshoe is nailed to one post for luck' }) },
  { file: 'gate.png', entry: A({ id: 'arena-gate', name: 'Arena gate', fit: 'w', size: 230, sign: 'ARENA', what: 'the entrance arch of a rodeo ring: two tall log posts with a heavy log crossbeam high overhead, a hanging board sign under the beam, and two crossed wooden practice swords with a battered round shield on top of the beam, seen square-on' }) },
  { file: 'stands.png', entry: A({ id: 'arena-stands', name: 'Stands', count: 2, fit: 'w', size: 260, what: 'wooden bleachers for a crowd to watch duels: rows of plank benches rising in steps on a timber frame, seen from the front, empty', ones: 'one long stand with three rising rows; one shorter stand with two rows and a little shade roof of patched canvas on poles' }) },
  { file: 'props.png', entry: A({ id: 'arena-props', name: 'Arena props', count: 4, size: 120, what: 'things that stand around a duelling ring', ones: 'a big curved war horn on a wooden stand; a weapon rack of wooden practice swords, round shields and staves; an iron brazier on three legs, unlit; a tall pole with a long pennant flag in red and gold' }) },
];

function doc() {
  const out = [
    '# The arena\'s art: the prompts for ChatGPT (v2.3.3730)',
    '',
    '<!-- GENERATED by tools/world/arena-art-prompts.mjs: edit the script, then run it. -->',
    '',
    'The four pictures the owner made for the arena, each from a prompt the Object Studio\'s own builder made (`public/tools/objects/prompts.js` `promptFor`), with the style key attached. The pictures that came back are kept in `assets/prop-source/arena/`; `tools/world/add-arena-art.mjs` cuts them into the game\'s art (`docs/specs/arena-art.md`).',
    '',
    'These entries are not in the Object Studio\'s catalog (`public/tools/objects/catalog.js`): a catalog change re-bakes both Wheels and deploys the worker, and this art comes into the game through `src/data/arenaArt.js` instead.',
    '',
  ];
  for (const { file, entry } of ARENA_PROMPTS) {
    out.push(`## ${entry.name}`, '', `- **Kept as:** \`assets/prop-source/arena/${file}\``, `- **Asked for:** ${entry.count === 1 ? 'one object' : `${entry.count} objects`}, ${entry.fit === 'w' ? 'the widest' : 'the tallest'} ${entry.size} game px ${entry.fit === 'w' ? 'wide' : 'tall'}${entry.frame === 'wide' ? ', on a wide 3:2 picture' : ''}`, '', '```text', promptFor(entry), '```', '');
  }
  return out.join('\n');
}

const text = doc();
if (process.argv.includes('--check')) {
  const have = fs.existsSync(DOC) ? fs.readFileSync(DOC, 'utf8') : '';
  if (have !== text) { console.error(`${path.relative(ROOT, DOC)} is stale: run node tools/world/arena-art-prompts.mjs`); process.exit(1); }
  console.log(`${path.relative(ROOT, DOC)} is up to date`);
} else {
  fs.writeFileSync(DOC, text);
  console.log(`wrote ${path.relative(ROOT, DOC)}`);
}
